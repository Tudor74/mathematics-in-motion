let lastCall = 0;
async function arxiv(params) {
  // Throttle per instance and, best effort, across instances via a shared timestamp.
  let shared = 0; try { shared = (await me.puter.kv.get(K('arxiv-last'))) || 0; } catch (e) {}
  const gap = Math.max(lastCall, shared) + WAIT - Date.now();
  if (gap > 0) await sleep(gap);
  lastCall = Date.now(); try { await me.puter.kv.set(K('arxiv-last'), lastCall); } catch (e) {}
  const qs = Object.entries(params).map(([k, v]) => k + '=' + encodeURIComponent(v)).join('&');
  for (let attempt = 0; ; attempt++) {
    const res = await fetch(API + '?' + qs, { headers: { 'User-Agent': UA } });
    if (res.ok) return res.text();
    // arXiv throttles shared egress addresses; back off briefly, then give up and let callers serve cache.
    if ((res.status === 429 || res.status === 503) && attempt < 2) { await sleep(6000 * (attempt + 1)); lastCall = Date.now(); continue; }
    throw new Error('arXiv responded ' + res.status);
  }
}

const decode = s => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
  .replace(/&#39;|&apos;/g, "'").replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(+n)).replace(/&amp;/g, '&');
const clean = s => decode(String(s || '')).replace(/\s+/g, ' ').trim();
const tag = (xml, name) => { const m = xml.match(new RegExp('<' + name + '(?:\\s[^>]*)?>([\\s\\S]*?)</' + name + '>')); return m ? m[1] : ''; };

function parseEntries(xml) {
  return [...xml.matchAll(/<entry>([\s\S]*?)<\/entry>/g)].map(([, e]) => {
    const abs = clean(tag(e, 'id'));
    const pc = e.match(/<arxiv:primary_category[^>]*term="([^"]+)"/);
    return {
      id: abs.replace(/^https?:\/\/arxiv\.org\/abs\//, ''),
      url: abs.replace(/^http:/, 'https:'),
      title: clean(tag(e, 'title')),
      authors: [...e.matchAll(/<author>\s*<name>([\s\S]*?)<\/name>/g)].map(m => clean(m[1])),
      published: clean(tag(e, 'published')).slice(0, 10),
      category: pc ? pc[1] : '',
      abstract: clean(tag(e, 'summary'))
    };
  });
}
const total = xml => { const m = xml.match(/totalResults[^>]*>\s*(\d+)\s*</); if (!m) throw new Error('No total in arXiv reply'); return +m[1]; };

const pad = n => String(n).padStart(2, '0');
function periods(now) {
  const y = now.getUTCFullYear(), m = now.getUTCMonth();
  const years = [];
  for (let k = FIRST_YEAR; k <= y; k++) years.push({ key: String(k), from: k + '01010000', to: k + '12312359', open: k === y });
  const months = [];
  for (let i = MONTHS - 1; i >= 0; i--) {
    const d = new Date(Date.UTC(y, m - i, 1)), yy = d.getUTCFullYear(), mm = d.getUTCMonth() + 1;
    const last = new Date(Date.UTC(yy, mm, 0)).getUTCDate();
    months.push({ key: yy + '-' + pad(mm), from: '' + yy + pad(mm) + '010000', to: '' + yy + pad(mm) + pad(last) + '2359', open: i === 0 });
  }
  return { years, months };
}

function text(r) {
  if (typeof r === 'string') return r;
  const c = r && r.message && r.message.content;
  if (typeof c === 'string') return c;
  if (Array.isArray(c)) return c.map(x => x.text || '').join('');
  return String(r || '');
}

async function summarise(topic, papers) {
  const list = papers.map((p, i) => `[${i + 1}] "${p.title}" (${p.published}, ${p.category})\n${p.abstract.slice(0, 1400)}`).join('\n\n');
  const prompt = `You write for an educational mathematics site. Field: ${topic.field}.
Below are the six most recent arXiv submissions in this area. Write ONE short paragraph of at most 3 sentences and at most 80 words, for a curious undergraduate, on what these submissions together suggest about where the field is moving and their likely impact. Be concise: name only the two or three most notable papers, and finish with a complete sentence.
Rules: British English; plain prose, no lists, no headings, no markdown; refer to papers by a short form of their title; these are preprints that have not been peer reviewed, so describe potential impact cautiously and do not invent results, citations or significance beyond the abstracts; if the papers are unrelated, say the batch spans several separate directions in one sentence.

${list}`;
  const r = await me.puter.ai.chat(prompt, { model: MODEL, max_tokens: 200, temperature: 0.3 });
  return wholeSentences(text(r).replace(/\s+/g, ' ').trim());
}

// If a reply was cut off, keep only its complete sentences (and at most ~90 words).
function wholeSentences(t) {
  const sentences = t.match(/[^.!?]+[.!?]+["'”’)]*(\s|$)/g) || [];
  let out = '';
  for (const s of sentences) { if ((out + s).split(/\s+/).length > 95 && out) break; out += s; }
  return (out || t).trim();
}

async function build(id, topic, { maxAge = VISITOR_MAX_AGE, budget = BUDGET, countsMaxAge = 2 * OPEN_TTL } = {}) {
  const start = Date.now(), now = new Date(), kv = me.puter.kv;
  const left = () => budget - (Date.now() - start);

  // 1 · Newest six submissions.
  let papers = await kv.get(K(id, 'papers'));
  let stale = false;
  if (!papers || Date.now() - papers.at > maxAge) {
    try {
      const xml = await arxiv({ search_query: topic.query, sortBy: 'submittedDate', sortOrder: 'descending', start: 0, max_results: 6 });
      papers = { at: Date.now(), list: parseEntries(xml) };
      await kv.set(K(id, 'papers'), papers);
    } catch (e) { if (!papers) throw e; stale = true; }
  }

  // 2 · Impact paragraph, once per distinct set of papers.
  const sig = 'v2:' + papers.list.map(p => p.id).join(',');  // bump the prefix to rewrite every summary
  let summary = await kv.get(K(id, 'summary'));
  if ((!summary || summary.sig !== sig) && papers.list.length) {
    summary = { sig, at: Date.now(), model: MODEL, text: await summarise(topic, papers.list) };
    await kv.set(K(id, 'summary'), summary);
  }

  // 3 · Counts: fill what the remaining budget allows, newest periods first.
  const { years, months } = periods(now);
  const counts = (await kv.get(K(id, 'counts'))) || {};
  const fresh = (key, open) => counts[key] && (!open || Date.now() - counts[key].at < countsMaxAge);
  const todo = [...months.slice().reverse(), ...years.slice().reverse()].filter(p => !fresh(p.key, p.open));
  for (const p of todo) {
    if (stale || left() < WAIT + 2500) break;
    try {
      const xml = await arxiv({ search_query: `${topic.query} AND submittedDate:[${p.from} TO ${p.to}]`, start: 0, max_results: 1 });
      counts[p.key] = { n: total(xml), at: Date.now() };
      await kv.set(K(id, 'counts'), counts);
    } catch (e) { stale = true; break; }
  }
  const row = p => ({ key: p.key, n: counts[p.key] ? counts[p.key].n : null, partial: p.open });

  return {
    lesson: id, name: topic.name, label: topic.label, query: topic.query, listing: topic.listing,
    papers: papers.list, papersAt: new Date(papers.at).toISOString(),
    summary: summary ? { text: summary.text, model: summary.model, at: new Date(summary.at).toISOString() } : null,
    years: years.map(row), months: months.map(row),
    complete: stale || [...years, ...months].every(p => counts[p.key]), stale,
    updated: now.toISOString()
  };
}

async function wikipedia(title) {
  const res = await fetch('https://en.wikipedia.org/api/rest_v1/page/summary/' + encodeURIComponent(title), { headers: { 'User-Agent': UA, 'Accept': 'application/json' } });
  if (!res.ok) throw new Error('Wikipedia responded ' + res.status);
  const d = await res.json();
  const sentences = String(d.extract || '').match(/[^.!?]+[.!?]+(\s|$)/g) || [d.extract || ''];
  return {
    url: d.content_urls && d.content_urls.desktop ? d.content_urls.desktop.page : 'https://en.wikipedia.org/wiki/' + title,
    description: d.description || '', bio: sentences.slice(0, 2).join('').trim(),
    image: d.thumbnail ? d.thumbnail.source : null
  };
}

async function people(id, topic, { budget = BUDGET } = {}) {
  const start = Date.now(), kv = me.puter.kv, left = () => budget - (Date.now() - start);
  const cache = (await kv.get(K(id, 'people2'))) || {};
  let arxivDown = false;
  for (const p of topic.people) {
    const c = cache[p.wiki] || {};
    if (!c.wiki || Date.now() - c.wiki.at > PEOPLE_TTL) {
      try { c.wiki = { at: Date.now(), ...(await wikipedia(p.wiki)) }; } catch (e) { c.wiki = c.wiki || null; }
    }
    if (!arxivDown && (!c.arxiv || Date.now() - c.arxiv.at > PEOPLE_TTL) && left() > WAIT + 2500) {
      try {
        const xml = await arxiv({ search_query: p.arxiv, sortBy: 'submittedDate', sortOrder: 'descending', start: 0, max_results: 1 });
        const [latest] = parseEntries(xml);
        c.arxiv = { at: Date.now(), count: total(xml), latest: latest ? { title: latest.title, url: latest.url, published: latest.published } : null };
      } catch (e) { arxivDown = true; }
    }
    cache[p.wiki] = c;
  }
  await kv.set(K(id, 'people2'), cache);
  const list = topic.people.map(p => {
    const c = cache[p.wiki] || {}, w = c.wiki || {};
    return {
      name: p.name, area: p.area, description: w.description || '', bio: w.bio || '', image: w.image || null,
      wikipedia: w.url || 'https://en.wikipedia.org/wiki/' + p.wiki,
      arxiv: { url: 'https://arxiv.org/search/?searchtype=author&query=' + encodeURIComponent(p.name.replace(/^W\. /, '')) + '&order=-announced_date_first', count: c.arxiv ? c.arxiv.count : null, latest: c.arxiv ? c.arxiv.latest : null },
      linkedin: 'https://www.linkedin.com/search/results/people/?keywords=' + encodeURIComponent(p.name)
    };
  });
  return { lesson: id, name: topic.name, note: topic.peopleNote, people: list, complete: arxivDown || list.every(p => p.arxiv.count != null && p.bio), stale: arxivDown, updated: new Date().toISOString() };
}

async function extractQuestions(topic, papers) {
  const list = papers.map((p, i) => `[${i + 1}] "${p.title}"\n${p.abstract.slice(0, 1400)}`).join('\n\n');
  const prompt = `Field: ${topic.field}. For each arXiv abstract below, identify the open problem, open question or conjecture it is about, using ONLY what the abstract says.
Return a JSON array with one object per abstract, in order: {"i": number, "question": string, "status": "settles" | "progress" | "poses" | "uses", "matches": string | null}.
- question: one plain-English sentence (max 30 words) stating the open question itself, understandable by a strong undergraduate; British English; no LaTeX.
- status: "settles" if the abstract claims to fully answer it, "progress" if it claims partial results, "poses" if it raises it as new or still open, "uses" if it only assumes or applies a conjecture.
- matches: the id from the list below if the paper is directly about that well-known question (the same question, not merely the same area), otherwise null.
${topic.open.map(o => `  ${o.id}: ${o.title} — ${o.q}`).join('\n')}
Output the JSON array only.

${list}`;
  const r = await me.puter.ai.chat(prompt, { model: MODEL, max_tokens: 900, temperature: 0.1 });
  const raw = text(r), m = raw.match(/\[[\s\S]*\]/);
  const arr = m ? JSON.parse(m[0]) : [];
  return papers.map((p, i) => {
    const q = arr.find(x => x && x.i === i + 1) || arr[i] || {};
    const status = ['settles', 'progress', 'poses', 'uses'].includes(q.status) ? q.status : 'poses';
    const matches = topic.open.some(o => o.id === q.matches) ? q.matches : null;
    return { question: String(q.question || '').trim(), status, matches, paper: { title: p.title, url: p.url, published: p.published, category: p.category, authors: p.authors } };
  }).filter(x => x.question);
}

async function openQuestions(id, topic, { maxAge = VISITOR_MAX_AGE } = {}) {
  const kv = me.puter.kv;
  let cache = await kv.get(K(id, 'open2'));
  const flags = (await kv.get(K(id, 'flags'))) || {};
  if (!cache || Date.now() - cache.at > maxAge) {
    let xml;
    try { xml = await arxiv({ search_query: openQuery(topic), sortBy: 'submittedDate', sortOrder: 'descending', start: 0, max_results: 6 }); }
    catch (e) { if (!cache) throw e; return { lesson: id, query: openQuery(topic), model: cache.model, at: new Date(cache.at).toISOString(), items: cache.items, flags, stale: true }; }
    const papers = parseEntries(xml), sig = papers.map(p => p.id).join(',');
    if (!cache || cache.sig !== sig) {
      cache = { sig, at: Date.now(), model: MODEL, items: await extractQuestions(topic, papers) };
      // Remember claims to settle a curated question, so the page can flag it for review.
      for (const it of cache.items) if (it.matches && it.status === 'settles') flags[it.matches] = { status: it.status, paper: it.paper, at: Date.now() };
      await kv.set(K(id, 'flags'), flags);
    } else cache.at = Date.now();
    await kv.set(K(id, 'open2'), cache);
  }
  const live = Object.fromEntries(Object.entries(flags).filter(([, f]) => Date.now() - f.at < FLAG_TTL));
  return { lesson: id, query: openQuery(topic), model: cache.model, at: new Date(cache.at).toISOString(), items: cache.items, flags: live };
}

// Owner-only helper used when preparing new lessons: checks that Wikipedia titles resolve.
async function isOwner(user) {
  if (!user || !user.puter) return false;
  const get = u => (u.puter.auth && u.puter.auth.getUser) ? u.puter.auth.getUser() : u.puter.getUser();
  const [a, b] = await Promise.all([get(user), get(me)]);
  return !!(a && b && a.uuid && a.uuid === b.uuid);
}

router.post('/admin/validate', async ({ request, user }) => {
  if (!(await isOwner(user))) return json({ error: 'Owner only' }, 403);
  const { wiki = [] } = await request.json();
  const out = {};
  for (const title of wiki.slice(0, 80)) {
    try { const w = await wikipedia(title); out[title] = { ok: true, description: w.description, bio: w.bio.slice(0, 160) }; }
    catch (e) { out[title] = { ok: false, error: String(e.message || e) }; }
  }
  return json(out);
});

router.get('/admin/usage', async ({ user }) => {
  if (!(await isOwner(user))) return json({ error: 'Owner only' }, 403);
  try { return json(await user.puter.auth.getMonthlyUsage()); }
  catch (e) { return json({ error: String(e.message || e) }, 502); }
});

router.post('/admin/arxiv-count', async ({ request, user }) => {
  if (!(await isOwner(user))) return json({ error: 'Owner only' }, 403);
  const { queries = [] } = await request.json();
  const out = {};
  for (const q of queries.slice(0, 6)) {
    try { const xml = await arxiv({ search_query: q, sortBy: 'submittedDate', sortOrder: 'descending', start: 0, max_results: 2 });
      out[q] = { count: total(xml), latest: parseEntries(xml).map(e => ({ title: e.title, authors: e.authors.slice(0, 4), published: e.published, category: e.category })) }; }
    catch (e) { out[q] = { error: String(e.message || e) }; }
  }
  return json(out);
});

// Scheduled refresh: each call refreshes the lesson whose data is oldest, within ~24 s.
async function ages(id) {
  const kv = me.puter.kv;
  const [papers, open, ppl] = await Promise.all([kv.get(K(id, 'papers')), kv.get(K(id, 'open2')), kv.get(K(id, 'people2'))]);
  const pplAt = ppl ? Math.min(...Object.values(ppl).map(c => (c.arxiv && c.arxiv.at) || 0)) : 0;
  return { papers: papers ? papers.at : 0, open: open ? open.at : 0, people: isFinite(pplAt) ? pplAt : 0 };
}
async function refreshNext() {
  const start = Date.now(), ids = Object.keys(TOPICS);
  const all = await Promise.all(ids.map(async id => ({ id, a: await ages(id) })));
  const score = x => Math.min(x.a.papers, x.a.open);
  all.sort((p, q) => score(p) - score(q));
  const pick = all[0], topic = TOPICS[pick.id], done = [];
  const elapsed = () => Date.now() - start;
  if (Date.now() - score(pick) < REFRESH_AGE) return { lesson: null, note: 'everything is fresh', ms: elapsed() };
  try { await build(pick.id, topic, { maxAge: REFRESH_AGE, budget: 12000, countsMaxAge: OPEN_TTL }); done.push('papers+summary+counts'); } catch (e) { done.push('papers failed: ' + (e.message || e)); }
  if (elapsed() < 14000) { try { await openQuestions(pick.id, topic, { maxAge: REFRESH_AGE }); done.push('open questions'); } catch (e) { done.push('open failed: ' + (e.message || e)); } }
  if (elapsed() < 15000 && Date.now() - pick.a.people > PEOPLE_TTL - 12 * 3600e3) { try { await people(pick.id, topic, { budget: 22000 - elapsed() }); done.push('people'); } catch (e) { done.push('people failed'); } }
  await me.puter.kv.set(K('last-refresh'), { lesson: pick.id, done, at: Date.now(), ms: elapsed() });
  return { lesson: pick.id, done, ms: elapsed() };
}
router.get('/refresh-next', async () => {
  try { return json(await refreshNext()); } catch (e) { return json({ error: String(e.message || e) }, 500); }
});
router.get('/refresh-status', async () => {
  const ids = Object.keys(TOPICS), now = Date.now();
  const rows = await Promise.all(ids.map(async id => { const a = await ages(id); const h = t => t ? Math.round((now - t) / 360e3) / 10 : null; return { id, papersHours: h(a.papers), openHours: h(a.open), peopleHours: h(a.people) }; }));
  return json({ last: await me.puter.kv.get(K('last-refresh')), lessons: rows, at: new Date(now).toISOString() });
});

