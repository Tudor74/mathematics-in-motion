#!/usr/bin/env node
// Regenerates the per-lesson research data in workers/research.js and index.html
// from research/topics.json (the single source). Run: node tools/build-research.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const topics = JSON.parse(fs.readFileSync(path.join(root, 'research/topics.json'), 'utf8'));

const problems = [];
for (const [id, t] of Object.entries(topics)) {
  for (const k of ['name', 'label', 'query', 'listing', 'field', 'peopleNote']) if (!t[k]) problems.push(`${id}: missing ${k}`);
  if (!Array.isArray(t.people) || t.people.length !== 6) problems.push(`${id}: needs 6 people`);
  if (!Array.isArray(t.openQuestions) || t.openQuestions.length !== 6) problems.push(`${id}: needs 6 open questions`);
  if (!Array.isArray(t.milestones) || t.milestones.length < 5) problems.push(`${id}: needs 5+ milestones`);
  (t.people || []).forEach((p, i) => ['name', 'wiki', 'arxiv', 'area'].forEach(k => p[k] || problems.push(`${id}: person ${i} missing ${k}`)));
  (t.openQuestions || []).forEach((q, i) => ['id', 'title', 'status', 'q', 'known', 'link'].forEach(k => q[k] || problems.push(`${id}: question ${i} missing ${k}`)));
  (t.milestones || []).forEach((m, i) => ['year', 'title', 'text'].forEach(k => m[k] || problems.push(`${id}: milestone ${i} missing ${k}`)));
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const worker = Object.fromEntries(Object.entries(topics).map(([id, t]) => [id, {
  name: t.name, label: t.label, query: t.query, listing: t.listing, field: t.field, peopleNote: t.peopleNote,
  people: t.people, open: t.openQuestions.map(q => ({ id: q.id, title: q.title, q: q.q }))
}]));
const page = Object.fromEntries(Object.entries(topics).map(([id, t]) => [id, {
  listing: t.listing, openQuestions: t.openQuestions, milestones: t.milestones
}]));

function splice(file, begin, end, body) {
  const p = path.join(root, file), s = fs.readFileSync(p, 'utf8');
  const a = s.indexOf(begin), b = s.indexOf(end);
  if (a < 0 || b < a) throw new Error(`markers not found in ${file}`);
  fs.writeFileSync(p, s.slice(0, a + begin.length) + '\n' + body + '\n' + s.slice(b));
}
splice('workers/research.js', '// BEGIN TOPICS (generated by tools/build-research.js from research/topics.json)', '// END TOPICS',
  'const TOPICS = ' + JSON.stringify(worker, null, 1) + ';');
splice('index.html', '/*RESEARCH-DATA:BEGIN (generated by tools/build-research.js)*/', '/*RESEARCH-DATA:END*/',
  'const RESEARCH_TOPICS=' + JSON.stringify(page) + ';');
console.log(`built ${Object.keys(topics).length} lesson(s): ${Object.keys(topics).join(', ')}`);
